// Current language state helper
export function getCurrentLanguage() {
  return localStorage.getItem('gcc_lang') || 'en';
}

export function setLanguage(lang) {
  const target = lang === 'ar' ? 'ar' : 'en';
  localStorage.setItem('gcc_lang', target);

  // Update HTML tag attributes
  document.documentElement.lang = target;
  document.documentElement.dir = target === 'ar' ? 'rtl' : 'ltr';

  if (target === 'ar') {
    document.body.classList.add('rtl-mode');
  } else {
    document.body.classList.remove('rtl-mode');
  }

  // Update all DOM elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (TRANSLATIONS[target] && TRANSLATIONS[target][key]) {
      el.textContent = TRANSLATIONS[target][key];
    }
  });

  // Update language switcher toggles
  document.querySelectorAll('.lang-toggle-btn').forEach((btn) => {
    const codeSpan = btn.querySelector('.lang-code');
    const labelSpan = btn.querySelector('.lang-label');
    if (codeSpan) codeSpan.textContent = TRANSLATIONS[target]['nav.langCode'];
    if (labelSpan) labelSpan.textContent = TRANSLATIONS[target]['nav.lang'];
  });

  // Dispatch global custom event for components
  window.dispatchEvent(new CustomEvent('gcc_language_changed', { detail: { lang: target } }));
}

// Initializer on every page load
export function initI18n() {
  const current = getCurrentLanguage();
  setLanguage(current);

  // Bind click listener to all language switcher buttons
  document.querySelectorAll('.lang-toggle-btn').forEach((btn) => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const currentLang = getCurrentLanguage();
      const nextLang = currentLang === 'en' ? 'ar' : 'en';
      setLanguage(nextLang);
    });
  });
}

// Helper to translate single key
export function t(key) {
  const lang = getCurrentLanguage();
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.en[key] || key;
}
